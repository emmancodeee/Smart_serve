/**
 * Analytics & Reporting Service
 * Provides registration funnel tracking, inventory turnover rates,
 * no-show rate analysis, and other aggregate reporting.
 */
const Registration = require('../models/Registration');
const Inventory = require('../models/Inventory');
const Schedule = require('../models/Schedule');
const Transaction = require('../models/Transaction');
const User = require('../models/User');
const { resolveAuthenticatedAdmin, isSuperAdminAccount } = require('./authSupportService');
const { cache, CACHE_KEYS } = require('./cacheService');
const logger = require('../utils/logger');

const ANALYTICS_CACHE_TTL = 10 * 60 * 1000; // 10 minutes

/**
 * Registration Funnel Tracking
 * Shows conversion rates across the registration lifecycle
 */
async function getRegistrationFunnel(req) {
  const { error } = await resolveAuthenticatedAdmin(req);
  if (error) return { error };

  const cacheKey = CACHE_KEYS.ANALYTICS_PREFIX + 'funnel';
  const cached = cache.get(cacheKey);
  if (cached) return { body: cached, fromCache: true };

  try {
    const totalUsers = await User.countDocuments({ isAdmin: { $ne: true }, isDeleted: { $ne: true } });
    const totalRegistrations = await Registration.countDocuments();
    const pendingRegistrations = await Registration.countDocuments({ status: 'pending' });
    const approvedRegistrations = await Registration.countDocuments({ status: 'approved' });
    const rejectedRegistrations = await Registration.countDocuments({ status: 'rejected' });
    const completedPickups = await Schedule.countDocuments({
      status: 'Completed',
      isAutoGenerated: true
    });
    const returnedItems = await Registration.countDocuments({ returnStatus: 'returned' });
    const noShows = await Schedule.countDocuments({
      status: 'No Show',
      isAutoGenerated: true
    });

    const funnel = {
      totalUsers,
      totalRegistrations,
      registrationRate: totalUsers > 0 ? (totalRegistrations / totalUsers * 100).toFixed(1) + '%' : '0%',
      byStatus: {
        pending: pendingRegistrations,
        approved: approvedRegistrations,
        rejected: rejectedRegistrations
      },
      approvalRate: totalRegistrations > 0
        ? (approvedRegistrations / totalRegistrations * 100).toFixed(1) + '%'
        : '0%',
      rejectionRate: totalRegistrations > 0
        ? (rejectedRegistrations / totalRegistrations * 100).toFixed(1) + '%'
        : '0%',
      conversion: {
        registered: totalRegistrations,
        approved: approvedRegistrations,
        pickedUp: completedPickups,
        returned: returnedItems
      },
      pickupRate: approvedRegistrations > 0
        ? (completedPickups / approvedRegistrations * 100).toFixed(1) + '%'
        : '0%',
      returnRate: completedPickups > 0
        ? (returnedItems / completedPickups * 100).toFixed(1) + '%'
        : '0%',
      noShows,
      noShowRate: completedPickups + noShows > 0
        ? (noShows / (completedPickups + noShows) * 100).toFixed(1) + '%'
        : '0%'
    };

    cache.set(cacheKey, funnel, ANALYTICS_CACHE_TTL);
    return { body: funnel };
  } catch (err) {
    logger.error('Registration funnel analytics failed', { error: err.message });
    return { error: { status: 500, body: { error: 'Analytics computation failed' } } };
  }
}

/**
 * Inventory Turnover Rate Aggregation
 * Shows how quickly inventory items are consumed and replenished
 */
async function getInventoryAnalytics(req) {
  const { error } = await resolveAuthenticatedAdmin(req);
  if (error) return { error };

  const cacheKey = CACHE_KEYS.ANALYTICS_PREFIX + 'inventory';
  const cached = cache.get(cacheKey);
  if (cached) return { body: cached, fromCache: true };

  try {
    const inventory = await Inventory.find().lean();
    const transactions = await Transaction.find({
      action: { $in: ['inventory_added', 'inventory_updated', 'inventory_deleted'] },
      createdAt: { $gte: new Date(Date.now() - 30 * 24 * 60 * 60 * 1000) } // Last 30 days
    }).lean();

    const analytics = {
      totalItems: inventory.length,
      totalQuantity: inventory.reduce((sum, item) => sum + (item.quantity || 0), 0),
      lowStockItems: inventory.filter(item => item.quantity <= item.reorderLevel).length,
      outOfStockItems: inventory.filter(item => item.quantity === 0).length,
      byCategory: {},
      recentActivity: {
        last30Days: transactions.length,
        additions: transactions.filter(t => t.action === 'inventory_added').length,
        updates: transactions.filter(t => t.action === 'inventory_updated').length,
        deletions: transactions.filter(t => t.action === 'inventory_deleted').length
      }
    };

    // Aggregate by category
    inventory.forEach(item => {
      const cat = item.category || 'Uncategorized';
      if (!analytics.byCategory[cat]) {
        analytics.byCategory[cat] = {
          count: 0,
          totalQuantity: 0,
          lowStockCount: 0
        };
      }
      analytics.byCategory[cat].count++;
      analytics.byCategory[cat].totalQuantity += item.quantity || 0;
      if (item.quantity <= item.reorderLevel) {
        analytics.byCategory[cat].lowStockCount++;
      }
    });

    cache.set(cacheKey, analytics, ANALYTICS_CACHE_TTL);
    return { body: analytics };
  } catch (err) {
    logger.error('Inventory analytics failed', { error: err.message });
    return { error: { status: 500, body: { error: 'Analytics computation failed' } } };
  }
}

/**
 * No-Show Rate by Module Analysis
 * Groups schedules by module to identify problematic pickup slots
 */
async function getNoShowAnalytics(req) {
  const { error } = await resolveAuthenticatedAdmin(req);
  if (error) return { error };

  const cacheKey = CACHE_KEYS.ANALYTICS_PREFIX + 'noshow';
  const cached = cache.get(cacheKey);
  if (cached) return { body: cached, fromCache: true };

  try {
    const schedules = await Schedule.find({
      isAutoGenerated: true,
      source: 'approval_auto_plan',
      status: { $in: ['Completed', 'No Show'] }
    }).lean();

    const byModule = {};
    let totalCompleted = 0;
    let totalNoShow = 0;

    schedules.forEach(schedule => {
      const module = schedule.module || 'General';
      if (!byModule[module]) {
        byModule[module] = { completed: 0, noShow: 0 };
      }
      if (schedule.status === 'Completed') {
        byModule[module].completed++;
        totalCompleted++;
      } else if (schedule.status === 'No Show') {
        byModule[module].noShow++;
        totalNoShow++;
      }
    });

    const moduleAnalytics = Object.entries(byModule)
      .map(([moduleName, stats]) => ({
        module: moduleName,
        completed: stats.completed,
        noShow: stats.noShow,
        total: stats.completed + stats.noShow,
        noShowRate: stats.completed + stats.noShow > 0
          ? (stats.noShow / (stats.completed + stats.noShow) * 100).toFixed(1) + '%'
          : '0%'
      }))
      .sort((a, b) => b.noShow - a.noShow);

    const result = {
      totalSchedules: totalCompleted + totalNoShow,
      totalCompleted,
      totalNoShow,
      overallNoShowRate: totalCompleted + totalNoShow > 0
        ? (totalNoShow / (totalCompleted + totalNoShow) * 100).toFixed(1) + '%'
        : '0%',
      byModule: moduleAnalytics
    };

    cache.set(cacheKey, result, ANALYTICS_CACHE_TTL);
    return { body: result };
  } catch (err) {
    logger.error('No-show analytics failed', { error: err.message });
    return { error: { status: 500, body: { error: 'Analytics computation failed' } } };
  }
}

/**
 * Get all analytics in a single response (dashboard overview)
 */
async function getDashboardAnalytics(req) {
  const { error } = await resolveAuthenticatedAdmin(req);
  if (error) return { error };

  const cacheKey = CACHE_KEYS.DASHBOARD_STATS;
  const cached = cache.get(cacheKey);
  if (cached) return { body: cached, fromCache: true };

  try {
    const [funnel, inventoryStats, noShowStats] = await Promise.all([
      Registration.aggregate([
        { $group: { _id: '$status', count: { $sum: 1 } } }
      ]),
      Inventory.aggregate([
        { $group: { _id: '$category', count: { $sum: 1 }, totalQty: { $sum: '$quantity' } } }
      ]),
      Schedule.aggregate([
        { $match: { isAutoGenerated: true, status: { $in: ['Completed', 'No Show'] } } },
        { $group: { _id: '$status', count: { $sum: 1 } } }
      ])
    ]);

    const funnelMap = {};
    funnel.forEach(item => { funnelMap[item._id] = item.count; });
    const noShowMap = {};
    noShowStats.forEach(item => { noShowMap[item._id] = item.count; });

    const dashboard = {
      registrations: {
        pending: funnelMap.pending || 0,
        approved: funnelMap.approved || 0,
        rejected: funnelMap.rejected || 0
      },
      inventory: {
        categories: inventoryStats.length,
        items: inventoryStats.reduce((sum, c) => sum + c.count, 0),
        totalQuantity: inventoryStats.reduce((sum, c) => sum + c.totalQty, 0)
      },
      pickups: {
        completed: noShowMap.Completed || 0,
        noShow: noShowMap['No Show'] || 0,
        noShowRate: (noShowMap.Completed || 0) + (noShowMap['No Show'] || 0) > 0
          ? ((noShowMap['No Show'] || 0) / ((noShowMap.Completed || 0) + (noShowMap['No Show'] || 0)) * 100).toFixed(1) + '%'
          : '0%'
      }
    };

    cache.set(cacheKey, dashboard, ANALYTICS_CACHE_TTL);
    return { body: dashboard };
  } catch (err) {
    logger.error('Dashboard analytics failed', { error: err.message });
    return { error: { status: 500, body: { error: 'Analytics computation failed' } } };
  }
}

module.exports = {
  getRegistrationFunnel,
  getInventoryAnalytics,
  getNoShowAnalytics,
  getDashboardAnalytics
};

