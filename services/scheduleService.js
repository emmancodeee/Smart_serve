const Schedule = require('../models/Schedule');
const Registration = require('../models/Registration');
const { logAdminTransaction } = require('./authSupportService');
const {
  countDailyLoadsFromSchedules,
  buildAutoScheduleForApprovedRegistration
} = require('../utils/scheduler');

function sanitizeText(value, fallback = '') {
  if (value === undefined || value === null) return fallback;
  return String(value).trim();
}

async function processNoShowReschedulesForUser(user) {
  const now = new Date();
  const missedPlans = await Schedule.find({
    userId: user._id,
    isAutoGenerated: true,
    source: 'approval_auto_plan',
    status: 'Planned',
    rescheduleConfirmationStatus: { $nin: ['Completed', 'Rejected'] },
    endTime: { $lt: now }
  })
    .sort({ startTime: 1 })
    .lean();

  if (!missedPlans.length) {
    return;
  }

  for (const missed of missedPlans) {
    await Schedule.updateOne(
      { _id: missed._id },
      {
        $set: {
          status: 'No Show',
          rescheduleConfirmationStatus: 'Rejected',
          rescheduleCompletedAt: new Date()
        }
      }
    );

    await logAdminTransaction(
      {
        _id: user._id,
        constructor: { modelName: 'User' },
        name: 'System Auto-Reject'
      },
      'pickup_confirmation_reject',
      'schedule',
      missed._id?.toString(),
      `${user?.name || 'User'} (${user?.email || 'no-email'}) did not complete the pickup request${missed?.module ? ` for ${missed.module}` : ''} before the deadline`
    );
  }
}

async function ensurePickupScheduleForApprovedUser(user) {
  const registration = await Registration.findOne({ userId: user._id });
  if (!registration || (user.status || '').toLowerCase() !== 'approved') {
    return;
  }

  const hasPlan = await Schedule.exists({
    userId: user._id,
    isAutoGenerated: true,
    source: 'approval_auto_plan'
  });
  if (hasPlan) {
    return;
  }

  const existingSchedules = await Schedule.find({ userId: user._id })
    .select('startTime endTime')
    .lean();

  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const allAutoPlans = await Schedule.find({
    isAutoGenerated: true,
    source: 'approval_auto_plan',
    startTime: { $gte: today }
  })
    .select('startTime')
    .lean();

  const dailyLoadMap = countDailyLoadsFromSchedules(allAutoPlans);
  const { events: generatedPlan } = await buildAutoScheduleForApprovedRegistration({
    userId: user._id,
    moduleName: registration.module || user.module || '',
    userName: user.name || 'Student',
    pickupDate: registration.pickupDate,
    existingSchedules,
    dailyLoadMap,
    maxPickupsPerDay: 100
  });

  if (generatedPlan.length) {
    await Schedule.insertMany(generatedPlan);
  }
}

async function getSchedulesForUser(userId) {
  return Schedule.find({ userId }).sort({ startTime: 1 }).lean();
}

async function getScheduleSummaryForUser(userId) {
  const schedules = await Schedule.find({ userId }).lean();
  const now = new Date();

  const upcomingEvents = schedules.filter(item =>
    item.status !== 'Cancelled' && new Date(item.startTime) >= now
  ).length;

  const busyHours = schedules.reduce((sum, item) => {
    const start = new Date(item.startTime).getTime();
    const end = new Date(item.endTime).getTime();
    if (!Number.isFinite(start) || !Number.isFinite(end) || end <= start) {
      return sum;
    }

    return sum + (end - start) / (1000 * 60 * 60);
  }, 0);

  return {
    totalSchedules: schedules.length,
    upcomingEvents,
    busyHours: Math.round(busyHours * 10) / 10
  };
}

async function checkConflictsForUser(userId, payload) {
  const startTime = new Date(payload?.startTime);
  const endTime = new Date(payload?.endTime);
  const excludeId = sanitizeText(payload?.excludeId);

  if (Number.isNaN(startTime.getTime()) || Number.isNaN(endTime.getTime()) || endTime <= startTime) {
    return { error: { status: 400, body: { error: 'Invalid start/end time' } } };
  }

  const query = {
    userId,
    startTime: { $lt: endTime },
    endTime: { $gt: startTime }
  };

  if (excludeId) {
    query._id = { $ne: excludeId };
  }

  const conflicts = await Schedule.find(query).select('_id title startTime endTime').lean();
  return {
    hasConflicts: conflicts.length > 0,
    conflicts
  };
}

function buildCreateSchedulePayload(userId, payload) {
  const title = sanitizeText(payload?.title);
  const startTime = new Date(payload?.startTime);
  const endTime = new Date(payload?.endTime);

  if (!title) {
    return { error: { status: 400, body: { error: 'Title is required' } } };
  }

  if (Number.isNaN(startTime.getTime()) || Number.isNaN(endTime.getTime()) || endTime <= startTime) {
    return { error: { status: 400, body: { error: 'Invalid start/end time' } } };
  }

  return {
    userId,
    title,
    type: sanitizeText(payload?.type, 'Task') || 'Task',
    description: sanitizeText(payload?.description),
    startTime,
    endTime,
    location: sanitizeText(payload?.location),
    module: sanitizeText(payload?.module),
    instructor: sanitizeText(payload?.instructor),
    priority: sanitizeText(payload?.priority, 'Medium') || 'Medium',
    reminders: Array.isArray(payload?.reminders)
      ? payload.reminders.filter(value => Number.isFinite(value)).map(Number)
      : [15],
    color: sanitizeText(payload?.color, '#3498db') || '#3498db',
    isRecurring: Boolean(payload?.isRecurring),
    recurrencePattern: payload?.isRecurring ? sanitizeText(payload?.recurrencePattern) || null : null,
    recurrenceEnd: payload?.isRecurring && payload?.recurrenceEnd ? new Date(payload.recurrenceEnd) : null
  };
}

async function createScheduleForUser(userId, payload) {
  const schedulePayload = buildCreateSchedulePayload(userId, payload);
  if (schedulePayload.error) {
    return schedulePayload;
  }

  const schedule = new Schedule(schedulePayload);
  await schedule.save();

  return {
    status: 201,
    body: { message: 'Schedule added', schedule }
  };
}

async function updateScheduleForUser(userId, scheduleId, payload) {
  const existingSchedule = await Schedule.findOne({ _id: scheduleId, userId })
    .select('_id isAutoGenerated');

  if (!existingSchedule) {
    return { error: { status: 404, body: { error: 'Schedule not found' } } };
  }

  if (existingSchedule.isAutoGenerated) {
    return {
      error: {
        status: 403,
        body: { error: 'Auto-generated pickup schedules cannot be edited by students.' }
      }
    };
  }

  const updates = {};
  const fields = ['title', 'type', 'description', 'location', 'module', 'instructor', 'priority', 'color', 'status'];
  fields.forEach(field => {
    if (payload?.[field] !== undefined) {
      updates[field] = sanitizeText(payload[field]);
    }
  });

  if (payload?.startTime !== undefined) {
    const startTime = new Date(payload.startTime);
    if (Number.isNaN(startTime.getTime())) {
      return { error: { status: 400, body: { error: 'Invalid start time' } } };
    }
    updates.startTime = startTime;
  }

  if (payload?.endTime !== undefined) {
    const endTime = new Date(payload.endTime);
    if (Number.isNaN(endTime.getTime())) {
      return { error: { status: 400, body: { error: 'Invalid end time' } } };
    }
    updates.endTime = endTime;
  }

  if (updates.startTime && updates.endTime && updates.endTime <= updates.startTime) {
    return { error: { status: 400, body: { error: 'End time must be after start time' } } };
  }

  if (Array.isArray(payload?.reminders)) {
    updates.reminders = payload.reminders.filter(value => Number.isFinite(value)).map(Number);
  }

  if (payload?.isRecurring !== undefined) {
    updates.isRecurring = Boolean(payload.isRecurring);
    updates.recurrencePattern = updates.isRecurring ? sanitizeText(payload?.recurrencePattern) || null : null;
    updates.recurrenceEnd = updates.isRecurring && payload?.recurrenceEnd ? new Date(payload.recurrenceEnd) : null;
  }

  const schedule = await Schedule.findOneAndUpdate(
    { _id: scheduleId, userId, isAutoGenerated: { $ne: true } },
    updates,
    { new: true }
  );

  if (!schedule) {
    return { error: { status: 404, body: { error: 'Schedule not found' } } };
  }

  return {
    body: { message: 'Schedule updated', schedule }
  };
}

async function deleteScheduleForUser(userId, scheduleId) {
  const existingSchedule = await Schedule.findOne({ _id: scheduleId, userId })
    .select('_id isAutoGenerated');

  if (!existingSchedule) {
    return { error: { status: 404, body: { error: 'Schedule not found' } } };
  }

  if (existingSchedule.isAutoGenerated) {
    return {
      error: {
        status: 403,
        body: { error: 'Auto-generated pickup schedules cannot be deleted by students.' }
      }
    };
  }

  const removed = await Schedule.findOneAndDelete({
    _id: scheduleId,
    userId,
    isAutoGenerated: { $ne: true }
  });

  if (!removed) {
    return { error: { status: 404, body: { error: 'Schedule not found' } } };
  }

  return {
    body: { message: 'Schedule deleted' }
  };
}

module.exports = {
  processNoShowReschedulesForUser,
  ensurePickupScheduleForApprovedUser,
  getSchedulesForUser,
  getScheduleSummaryForUser,
  checkConflictsForUser,
  createScheduleForUser,
  updateScheduleForUser,
  deleteScheduleForUser
};
