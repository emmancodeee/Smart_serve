const mongoose = require('mongoose');

const scheduleSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true
    },
    title: {
      type: String,
      required: true,
      trim: true
    },
    type: {
      type: String,
      enum: ['Class', 'Study', 'Exam', 'Task', 'Reminder', 'AI Plan'],
      default: 'Task'
    },
    description: {
      type: String,
      default: ''
    },
    startTime: {
      type: Date,
      required: true,
      index: true
    },
    endTime: {
      type: Date,
      required: true
    },
    location: {
      type: String,
      default: ''
    },
    module: {
      type: String,
      default: ''
    },
    instructor: {
      type: String,
      default: ''
    },
    priority: {
      type: String,
      enum: ['Low', 'Medium', 'High', 'Critical'],
      default: 'Medium'
    },
    status: {
      type: String,
      enum: ['Planned', 'In Progress', 'Completed', 'Cancelled', 'No Show'],
      default: 'Planned'
    },
    reminders: {
      type: [Number],
      default: [15]
    },
    color: {
      type: String,
      default: '#3498db'
    },
    isRecurring: {
      type: Boolean,
      default: false
    },
    recurrencePattern: {
      type: String,
      enum: ['daily', 'weekly', 'monthly', null],
      default: null
    },
    recurrenceEnd: {
      type: Date,
      default: null
    },
    isAutoGenerated: {
      type: Boolean,
      default: false
    },
    source: {
      type: String,
      default: ''
    },
    rescheduleConfirmationStatus: {
      type: String,
      enum: ['Pending', 'Confirmed', 'Adjusted', 'Completed', 'Rejected', null],
      default: null
    },
    rescheduleConfirmedAt: {
      type: Date,
      default: null
    },
    rescheduleAdjustedAt: {
      type: Date,
      default: null
    },
    rescheduleCompletedAt: {
      type: Date,
      default: null
    },
    originalMissedScheduleId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null
    }
  },
  { timestamps: true }
);

scheduleSchema.index({ userId: 1, startTime: 1, endTime: 1 });

module.exports = mongoose.model('Schedule', scheduleSchema);
