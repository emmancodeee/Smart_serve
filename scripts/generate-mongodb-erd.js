const entityMap = Object.fromEntries(entities.map((entity) => [entity.key, entity]));

function esc(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function anchor(entityKey, side, ratio = 0.5) {
  const entity = entityMap[entityKey];
  if (!entity) {
    throw new Error(`Unknown entity: ${entityKey}`);
  }

  if (side === 'left') return { x: entity.x, y: entity.y + entity.h * ratio };
  if (side === 'right') return { x: entity.x + entity.w, y: entity.y + entity.h * ratio };
  if (side === 'top') return { x: entity.x + entity.w * ratio, y: entity.y };
  if (side === 'bottom') return { x: entity.x + entity.w * ratio, y: entity.y + entity.h };
  throw new Error(`Unknown side: ${side}`);
}

function renderEntity(entity) {
  const headerColor = entity.type === 'embedded' ? theme.embeddedHeader : theme.header;
  const fillColor = entity.type === 'embedded' ? theme.embeddedPanel : theme.panel;

  const rows = entity.fields
    .map((field, index) => {
      const y = entity.y + HEADER_HEIGHT + 23 + index * ROW_HEIGHT;
      const dividerY = entity.y + HEADER_HEIGHT + index * ROW_HEIGHT;
      const divider = index === 0
        ? ''
        : `<line x1="${entity.x}" y1="${dividerY}" x2="${entity.x + entity.w}" y2="${dividerY}" stroke="${theme.softBorder}" stroke-width="1" opacity="0.55" />`;

      return `${divider}<text x="${entity.x + PADDING_X}" y="${y}" font-family="Arial, Helvetica, sans-serif" font-size="18" fill="${theme.text}">${esc(field)}</text>`;
    })
    .join('');

  return `
    <g>
      <rect x="${entity.x}" y="${entity.y}" width="${entity.w}" height="${entity.h}" rx="${CARD_RADIUS}" fill="${fillColor}" stroke="${theme.border}" stroke-width="2.2" />
      <rect x="${entity.x}" y="${entity.y}" width="${entity.w}" height="${HEADER_HEIGHT}" rx="${CARD_RADIUS}" fill="${headerColor}" />
      <rect x="${entity.x}" y="${entity.y + HEADER_HEIGHT - CARD_RADIUS}" width="${entity.w}" height="${CARD_RADIUS}" fill="${headerColor}" />
      <text x="${entity.x + PADDING_X}" y="${entity.y + 29}" font-family="Arial, Helvetica, sans-serif" font-size="21" font-weight="700" fill="${theme.title}">${esc(entity.title)}</text>
      ${rows}
    </g>
  `;
}

function renderLabel(x, y, text) {
  const width = Math.max(100, text.length * 8 + 20);
  const rectX = x - width / 2;
  const rectY = y - 14;
  return `
    <rect x="${rectX}" y="${rectY}" width="${width}" height="28" rx="14" fill="${theme.noteFill}" stroke="${theme.softBorder}" stroke-width="1.2" />
    <text x="${x}" y="${y + 6}" text-anchor="middle" font-family="Arial, Helvetica, sans-serif" font-size="16" fill="${theme.muted}">${esc(text)}</text>
  `;
}

function renderPolyline(points, options = {}) {
  const {
    stroke = theme.solidLine,
    width = 3,
    dash = '',
    label = '',
    labelX = 0,
    labelY = 0
  } = options;

  const pointString = points.map((point) => `${point.x},${point.y}`).join(' ');
  return `
    <polyline points="${pointString}" fill="none" stroke="${stroke}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round" ${dash ? `stroke-dasharray="${dash}"` : ''} />
    ${label ? renderLabel(labelX, labelY, label) : ''}
  `;
}

function renderPath(d, options = {}) {
  const {
    stroke = theme.solidLine,
    width = 3,
    dash = '',
    label = '',
    labelX = 0,
    labelY = 0
  } = options;

  return `
    <path d="${d}" fill="none" stroke="${stroke}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round" ${dash ? `stroke-dasharray="${dash}"` : ''} />
    ${label ? renderLabel(labelX, labelY, label) : ''}
  `;
}

